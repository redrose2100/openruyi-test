source "${OET_PATH}/libs/locallibs/common_lib.sh"

function pre_test()
{
    LOG_INFO "Start to prepare the test environment."
    DNF_INSTALL "hwloc"
    LOG_INFO "End to prepare the test environment."
}

function run_test() {
    LOG_INFO "Start to run test."
    hwloc-compress-dir -h | grep "hwloc-compress-dir \[options\]"
    CHECK_RESULT $? 0 0 "hwloc-compress-dir -h failed"
    hwloc-compress-dir --help | grep "hwloc-compress-dir \[options\]"
    CHECK_RESULT $? 0 0 "hwloc-compress-dir --help failed"
    hwloc-compress-dir --version | grep "hwloc-compress-dir"
    CHECK_RESULT $? 0 0 "hwloc-compress-dir --version failed"
    LOG_INFO "End of the test."
}

function post_test()
{
    LOG_INFO "Start to restore the test environment."
    DNF_REMOVE "$@"
    LOG_INFO "End to restore the test environment."
}

main "$@"
