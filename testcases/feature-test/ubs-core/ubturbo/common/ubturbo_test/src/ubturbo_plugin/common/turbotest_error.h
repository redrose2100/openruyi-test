#ifndef TURBOTEST_ERROR_H
#define TURBOTEST_ERROR_H

#include <cstdint>

namespace turbotest{
    using TURBOTEST_RES = uint32_t;
    using TurbotestResult = uint32_t;


#define TURBOTEST_ERROR_BEGIN_USER 0X1000
#define TURBOTEST_ERROR_USERNO(n) (uint32_t(TURBOTEST_ERROR_BEGIN_USER + (n)))
#define TURBOTEST_MID_HI16(MID) (uint32_t((MID) << 16))

#define TURBOTEST_MID_BEGIN0 0x0000
#define TURBOTEST_MID_BEGIN1 0x1000

#define TURBOTEST_COMMON_ERROR(n) (uint32_t(TURBOTEST_MID_BEGIN0 + (n)))
#define TURBOTEST_MID_MAKE_MANAGER(n)  (uint32_t(TURBOTEST_MID_BEGIN1 + (n)))

#define TURBOTEST_MASTER_MID_BASE TURBOTEST_MID_MAKE_MANAGER(1)
#define TURBOTEST_MASTER_MID_VM TURBOTEST_MID_MAKE_MANAGER(2)
#define TURBOTEST_MASTER_MID_MEM TURBOTEST_MID_MAKE_MANAGER(3)

#define TURBOTEST_AGENT_MID_BASE TURBOTEST_MID_MAKE_MANAGER(4)
#define TURBOTEST_AGENT_MID_VM TURBOTEST_MID_MAKE_MANAGER(5)
#define TURBOTEST_AGENT_MID_MEM TURBOTEST_MID_MAKE_MANAGER(6)

#define TURBOTEST_CLOUD_ADAPTER_MID TURBOTEST_MID_MAKE_MANAGER(7)

#define TURBOTEST_COMMUNICATION_MID_NET TURBOTEST_MID_MAKE_MANAGER(8)
#define TURBOTEST_COMMUNICATION_MID_HTTP TURBOTEST_MID_MAKE_MANAGER(9)

#define TURBOTEST_DB_MID_LDC TURBOTEST_MID_MAKE_MANAGER(10)

#define TURBOTEST_SERIALIZE_MID_BASE TURBOTEST_MID_MAKE_MANAGER(11)

#define TURBOTEST_MONITOR_MID_BASE TURBOTEST_MID_MAKE_MANAGER(12)

#define TURBOTEST_ERROR_SIGN_INT (-1)
#define TURBOTEST_OK TURBOTEST_COMMON_ERROR(0)
#define TURBOTEST_ERROR TURBOTEST_COMMON_ERROR(1)
#define TURBOTEST_ERROR_NOENT TURBOTEST_COMMON_ERROR(2)
#define TURBOTEST_ERROR_NOMEM TURBOTEST_COMMON_ERROR(3)
#define TURBOTEST_ERROR_ACCES TURBOTEST_COMMON_ERROR(4)
#define TURBOTEST_ERROR_SRCH TURBOTEST_COMMON_ERROR(5)
#define TURBOTEST_ERROR_EXIST TURBOTEST_COMMON_ERROR(6)
#define TURBOTEST_ERROR_NOSPC TURBOTEST_COMMON_ERROR(7)
#define TURBOTEST_ERROR_AGAIN TURBOTEST_COMMON_ERROR(8)
#define TURBOTEST_ERROR_IO TURBOTEST_COMMON_ERROR(9)
#define TURBOTEST_ERROR_BADF TURBOTEST_COMMON_ERROR(10)
#define TURBOTEST_ERROR_CONF_INVALID TURBOTEST_COMMON_ERROR(11)
#define TURBOTEST_ERROR_NULLPTR TURBOTEST_COMMON_ERROR(12)
#define TURBOTEST_MASTER_EMPTY_VECTOR_ERROR TURBOTEST_COMMON_ERROR(13)

#define TURBOTEST_ERROR_INVAL TURBOTEST_COMMON_ERROR(14)
#define TURBOTEST_ERROR_EXCEEDS_RANGE TURBOTEST_COMMON_ERROR(15)
#define TURBOTEST_WARN TURBOTEST_COMMON_ERROR(16)

#define TURBOTEST_INVALID_STRATEGY_ERROR \
    (TURBOTEST_MID_HI16(TURBOTEST_MASTER_MID_VM) | TURBOTEST_ERROR_USERNO(0x00))
        
#define TURBOTEST_RECLAIM_MEMORY_ERROR \
    (TURBOTEST_MID_HI16(TURBOTEST_MASTER_MID_VM) | TURBOTEST_ERROR_USERNO(0x01))

#define TURBOTEST_MIGRATE_ERROR \
    (TURBOTEST_MID_HI16(TURBOTEST_MASTER_MID_VM) | TURBOTEST_ERROR_USERNO(0x02))
        
#define TURBOTEST_INVALID_PARAM_ERROR \
    (TURBOTEST_MID_HI16(TURBOTEST_MASTER_MID_VM) | TURBOTEST_ERROR_USERNO(0x03))

#define TURBOTEST_RESULT_FAIL(ret)(static_cast<VmResult>(ret) != TURBOTEST_OK)
#define TURBOTEST_RESULT_OK(ret)(static_cast<VmResult>(ret) == TURBOTEST_OK)

#define TURBOTEST_ERROR_SERIALIZE_ERROR (TURBOTEST_MID_HI16(TURBOTEST_SERIALIZE_MID_BASE) | \
        TURBOTEST_ERROR_USERNO(0x00))

#define TURBOTEST_ERROR_DESERIALIZE_ERROR (TURBOTEST_MID_HI16(TURBOTEST_SERIALIZE_MID_BASE) | \
        TURBOTEST_ERROR_USERNO(0x01))

#define TURBOTEST_ERROR_SERIALIZE_DESERIALIZE_COMMON_ERROR (TURBOTEST_MID_HI16(TURBOTEST_SERIALIZE_MID_BASE) | \
        TURBOTEST_ERROR_USERNO(0x02))
}

#endif // TURBOTEST_ERROR_H