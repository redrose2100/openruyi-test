source ${OET_PATH}/libs/locallibs/common_lib.sh

function pre_test() {
    LOG_INFO "Start to prepare the test environment"
    DNF_INSTALL "libsmi"
    cp /usr/share/mibs/ietf/IF-MIB IF-MIB
    LOG_INFO "End to prepare the test environment"
}
function run_test() {
    LOG_INFO "Start to run testcase:oe_test_libsmi_smidump_06."
    smidump -f types IF-MIB >result.types 2>&1 && grep -e "# IF-MIB type derivation tree" result.types
    CHECK_RESULT $? 0 0 "L$LINENO: -f types No Pass"
    smidump -f types --types-no-implicit IF-MIB >result.types 2>&1 && grep -e "# IF-MIB type derivation tree" result.types
    CHECK_RESULT $? 0 0 "L$LINENO: -f types --types-no-implicit No Pass"
    smidump -f sizes IF-MIB >result.sizes 2>&1 && grep -E '[.*]' result.sizes | head -5
    CHECK_RESULT $? 0 0 "L$LINENO: -f sizes No Pass"
    smidump -f sizes --sizes-variables IF-MIB >result.sizes 2>&1 && grep -E '[.*]' result.sizes | head -5
    CHECK_RESULT $? 0 0 "L$LINENO: -f sizes --sizes-variables No Pass"
    smidump -f xml IF-MIB >result.xml 2>&1 && grep -e "This module has been generated by smidump" result.xml
    CHECK_RESULT $? 0 0 "L$LINENO: -f xml No Pass"
    smidump -f xml --xml-no-schema IF-MIB >result.xml 2>&1 && grep -e "This module has been generated by smidump" result.xml
    CHECK_RESULT $? 0 0 "L$LINENO: -f xml --xml-no-schema No Pass"
    smidump -f xml --xml-no-doctype IF-MIB >result.xml 2>&1 && grep -e "This module has been generated by smidump" result.xml
    CHECK_RESULT $? 0 0 "L$LINENO: -f xml --xml-no-doctype No Pass"
    smidump -f compliances IF-MIB >result.compliances 2>&1 && grep -e "+mr-n" result.compliances | head -5
    CHECK_RESULT $? 0 0 "L$LINENO: -f compliances No Pass"
    smidump -f boilerplate IF-MIB >result.boilerplate 2>&1 && grep -e "# IF-MIB security considerations boilerplate" result.boilerplate
    CHECK_RESULT $? 0 0 "L$LINENO: -f boilerplate No Pass"
    LOG_INFO "End to run test."

}
function post_test() {
    LOG_INFO "Start to restore the test environment."
    DNF_REMOVE
    rm -rf ./result* ./IF_MIB* ./IF-MIB* ./if-mib*
    LOG_INFO "End to restore the test environment."
}

main "$@"
