source "${OET_PATH}"/testcases/cli-test/elasticMem/common/em_common.sh

function pre_test() {
    LOG_INFO "Start environmental preparation."
    em_check_env || exit 255
    em_install_elasticmem || exit 255
    em_backup_config
    em_stop_service
    LOG_INFO "End of environmental preparation!"
}

function run_test() {
    LOG_INFO "Start testing..."
    # whitelist must be non-empty, otherwise paral mode init fails
    for level in debug info warn error; do
        cat > "$CONFIG_PATH" << EOF
policy = paral
log_level = $level
log_file = $LOG_FILE
whitelist = [test]
comm_whitelist = []
nr_cpus=1
memory_migration = true
sample_interval = 100
sample_count = 10
EOF
        em_start_service "service failed with log_level=$level"
        log_count=$(em_log_count "")
        [ "$log_count" -gt 0 ]
        CHECK_RESULT $? 0 0 "no log output for level=$level"
    done
    LOG_INFO "Finish test!"
}

function post_test() {
    LOG_INFO "start environment cleanup."
    em_kill_bg
    em_stop_service
    em_restore_config
    em_remove_elasticmem
    LOG_INFO "Finish environment cleanup!"
}

main "$@"
