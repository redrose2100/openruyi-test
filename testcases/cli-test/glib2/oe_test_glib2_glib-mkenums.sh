# shellcheck disable=SC2119
source "${OET_PATH}"/libs/locallibs/common_lib.sh

function pre_test() {
    LOG_INFO "Start to prepare the test environment."
    DNF_INSTALL "glib2 glib2-devel"
    cat > /tmp/test_enums.h << 'EOF'
#include <glib-object.h>

typedef enum
{
  TEST_ENUM_VALUE_A = 0,
  TEST_ENUM_VALUE_B = 1,
  TEST_ENUM_VALUE_C = 2
} TestEnum;

GType test_enum_get_type (void);
EOF
    cat > /tmp/test_mkenums.template << 'TMPL'
@BEGIN@
/* Template Header */
@BODY@
/* Template Footer */
@END@
TMPL
    LOG_INFO "End to prepare the test environment."
}

function run_test() {
    LOG_INFO "Start to run test."
    
    # Test --help (only one help test)
    glib-mkenums --help | grep -i "Usage\|usage"
    CHECK_RESULT $? 0 0 "glib-mkenums --help check failed"
    
    # Test --version
    glib-mkenums --version | grep "$(rpm -q glib2 | awk -F '-' '{print $2}')"
    CHECK_RESULT $? 0 0 "glib-mkenums --version check failed"
    
    # Test basic usage (generates output)
    glib-mkenums /tmp/test_enums.h | grep -q "generated by glib-mkenums"
    CHECK_RESULT $? 0 0 "glib-mkenums basic output check failed"
    
    # Test --identifier-prefix
    glib-mkenums --identifier-prefix MyPrefix /tmp/test_enums.h  | grep -q "generated by glib-mkenums"
    CHECK_RESULT $? 0 0 "glib-mkenums --identifier-prefix output check failed"
    
    # Test --symbol-prefix
    glib-mkenums --symbol-prefix my_sym /tmp/test_enums.h | grep -q "generated by glib-mkenums"
    CHECK_RESULT $? 0 0 "glib-mkenums --symbol-prefix output check failed"
    
    # Test --fhead (file header)
    glib-mkenums --fhead '/* Custom File Header */' /tmp/test_enums.h 2>&1 | grep "Custom File Header"
    CHECK_RESULT $? 0 0 "glib-mkenums --fhead check failed"
    
    # Test --ftail (file footer)
    glib-mkenums --ftail '/* Custom File Footer */' /tmp/test_enums.h 2>&1 | grep "Custom File Footer"
    CHECK_RESULT $? 0 0 "glib-mkenums --ftail check failed"
    
    # Test --fprod (per file)
    glib-mkenums --fprod '/* Processing file */' /tmp/test_enums.h 2>&1 | grep "Processing file"
    CHECK_RESULT $? 0 0 "glib-mkenums --fprod check failed"
    
    # Test --eprod (per enum, @ENUMNAME@ is replaced with enum name, requires --fprod)
    glib-mkenums --fprod '' --eprod '/* Enum: @ENUMNAME@ */' /tmp/test_enums.h 2>&1 | grep "TEST_ENUM"
    CHECK_RESULT $? 0 0 "glib-mkenums --eprod check failed"
    
    # Test --vhead (value header, requires --fprod and --eprod)
    glib-mkenums --fprod '' --eprod '' --vhead '/* Values: */' /tmp/test_enums.h 2>&1 | grep "Values:"
    CHECK_RESULT $? 0 0 "glib-mkenums --vhead check failed"
    
    # Test --vprod (per value, @VALUENAME@ is replaced with value name, requires --fprod and --eprod)
    glib-mkenums --fprod '' --eprod '' --vprod '/* Value: @VALUENAME@ */' /tmp/test_enums.h 2>&1 | grep "TEST_ENUM_VALUE_A"
    CHECK_RESULT $? 0 0 "glib-mkenums --vprod check failed"
    
    # Test --vtail (value tail, requires --fprod and --eprod)
    glib-mkenums --fprod '' --eprod '' --vtail '/* End of values */' /tmp/test_enums.h 2>&1 | grep "End of values"
    CHECK_RESULT $? 0 0 "glib-mkenums --vtail check failed"
    
    # Test --comments
    glib-mkenums --comments '/* Comment for @ENUMNAME@ */' /tmp/test_enums.h 2>&1 | grep "Comment for"
    CHECK_RESULT $? 0 0 "glib-mkenums --comments check failed"
    
    # Test --template
    glib-mkenums --template /tmp/test_mkenums.template /tmp/test_enums.h 2>&1 | grep -c "generated by glib-mkenums"
    CHECK_RESULT $? 0 0 "glib-mkenums --template check failed"
    
    # Test --output
    glib-mkenums --output=/tmp/test_mkenums_output.h /tmp/test_enums.h 2>&1
    CHECK_RESULT $? 0 0 "glib-mkenums --output check failed"
    grep -q "generated by glib-mkenums" /tmp/test_mkenums_output.h
    CHECK_RESULT $? 0 0 "glib-mkenums --output content check failed"
    
    LOG_INFO "End to run test."
}

function post_test() {
    LOG_INFO "Start to restore the test environment."
    DNF_REMOVE
    rm -f /tmp/test_enums.h /tmp/test_mkenums.template /tmp/test_mkenums_output.h
    LOG_INFO "End to restore the test environment."
}

main "$@"
