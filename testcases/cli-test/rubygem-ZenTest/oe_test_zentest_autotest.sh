source "$OET_PATH/libs/locallibs/common_lib.sh"
function pre_test() {
    LOG_INFO "Start to prepare the test environment."
    DNF_INSTALL "rubygem-ZenTest tar rubygem-test-unit"
    tar -xvf ./common/data.tar.gz > /dev/null
    multigem
    sed -i "/root_dir / aroot_dir = File.expand_path('..',__FILE__)" /usr/share/gems/gems/ZenTest-*/bin/multiruby
    LOG_INFO "End to prepare the test environment."
}
function run_test() {
    LOG_INFO "Start to run test."
    autotest --help | grep "Continuous testing for your ruby app"
    CHECK_RESULT $? 0 0 "Check autotest --help failed"
    unit_diff -h 2>&1 | grep -e "test.rb | unit_diff \[options]"
    CHECK_RESULT $? 0 0 "Check unit_diff -h failed"
    unit_diff -v | grep "$(rpm -qa rubygem-ZenTest | awk -F '-' '{print $3}')"
    CHECK_RESULT $? 0 0 "Check unit_diff -v failed"
    zentest ./data/testvideostore.rb ./data/videostore.rb | unit_diff -b | grep "classname: asrt"
    CHECK_RESULT $? 0 0 "Check unit_diff -b failed"
    zentest ./data/testvideostore.rb ./data/videostore.rb | unit_diff -c | grep "Number of errors detected"
    CHECK_RESULT $? 0 0 "Check unit_diff -c failed"
    zentest ./data/testvideostore.rb ./data/videostore.rb | unit_diff -k | grep "3 errors"
    CHECK_RESULT $? 0 0 "Check unit_diff -k failed"
    zentest ./data/testvideostore.rb ./data/videostore.rb | unit_diff -u | grep "Code Generated by ZenTest"
    CHECK_RESULT $? 0 0 "Check unit_diff -u failed"
    zentest ./data/testvideostore.rb ./data/videostore.rb | unit_diff -p
    CHECK_RESULT $? 0 0 "Check unit_diff -p failed"
    multigem | grep "TOTAL RESULT"
    CHECK_RESULT $? 0 0 "Check multigem failed"
    multiruby | grep "TOTAL RESULT"
    CHECK_RESULT $? 0 0 "Check multiruby failed"
    LOG_INFO "End to run test."
}
function post_test() {
    LOG_INFO "Start to restore the test environment."
    DNF_REMOVE "$@"
    rm -rf tmp.txt lib/ data/
    LOG_INFO "End to restore the test environment."
}
main "$@"
