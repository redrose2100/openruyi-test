source "$OET_PATH/libs/locallibs/common_lib.sh"
GEM_PACKAGES=" rubygem-test-unit rubygem-ZenTest rubygem-minitest rubygem-rails "
OTHER_DEPENDENCES=" tar nodejs bc gcc libyaml-devel ruby-devel "
SOURCE_URL="https://gems.ruby-china.com/"
ORIGIN_SOURCE="https://rubygems.org/"
function pre_test() {
    LOG_INFO "Start to prepare the test environment."
    # remove
    sudo dnf autoremove gem -y
    sudo rm -rf /usr/share/gems
    # install
    DNF_INSTALL "${GEM_PACKAGES} ${OTHER_DEPENDENCES}"
    gem sources --add ${SOURCE_URL} --remove ${ORIGIN_SOURCE}
    bundle config mirror.${ORIGIN_SOURCE} ${SOURCE_URL}
    yum groupinstall "Development Tools" -y
    tar -xvf ./common/data.tar.gz >/dev/null
    LOG_INFO "End to prepare the test environment."
}
function run_test() {
    LOG_INFO "Start to run test."
    zentest -h | grep "ZenTest scans your target"
    CHECK_RESULT $? 0 0 "Check zentest -h failed"
    zentest -v | grep "$(rpm -qa rubygem-ZenTest | awk -F '-' '{print $3}')"
    CHECK_RESULT $? 0 0 "Check zentest -v failed"
    zentest ./data/example1.rb ./data/example2.rb | grep "Code Generated by ZenTest"
    CHECK_RESULT $? 0 0 "Check zentest basic failed"
    zentest -e ./data/example1.rb | grep "NotImplementedError"
    CHECK_RESULT $? 0 0 "Check zentest -e failed"
    zentest -t ./data/example1.rb | grep "class TestThingy < Test::Unit::TestCase"
    CHECK_RESULT $? 0 0 "Check zentest -t failed"
    version=$(ruby --version | awk '{print $2}' | cut -c1-3)
    if [[ $(echo "${version} >= 2.6" | bc) -eq 1 ]] && [[ $(echo "${version} < 4.0" | bc) -eq 1 ]]; then
        rails new demo
        pushd demo || exit
        zentest -r ./db/seeds.rb | grep "Number of errors"
        CHECK_RESULT $? 0 0 "Check zentest -r failed"
        popd || exit
    fi
    LOG_INFO "End to run test."
}
function post_test() {
    LOG_INFO "Start to restore the test environment."
    DNF_REMOVE "$@"
    rm -rf lib/ data/ demo
    LOG_INFO "End to restore the test environment."
}
main "$@"
