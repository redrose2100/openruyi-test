source ${OET_PATH}/libs/locallibs/common_lib.sh

# 测试对象、测试需要的工具等安装准备
function pre_test() {
    LOG_INFO "Start to prepare the test environment."
    LOG_INFO "No pkgs need to install."
    LOG_INFO "End to prepare the test environment."
}

# 测试点的执行
function run_test() {
    LOG_INFO "Start to run test."
    #display SHA1 digest generated by specfile set
    restorecon_xattr -v /etc/
    CHECK_RESULT $? 0 0 "failed to display SHA1 digest"
    #Do not append "Match" or "No Match" to displayed digests
    restorecon_xattr -n /etc/
    CHECK_RESULT $? 0 0 "append "Match""
    #recursively descend directories
    restorecon_xattr -r /etc/
    CHECK_RESULT $? 0 0 "failed to recursively descend directories"
    #delete all non-matching security.sehash directory digest entries
    restorecon_xattr -d /etc/
    CHECK_RESULT $? 0 0 "failed to delete all non-matching security.sehash directory digest entries"
    #delete all security.sehash directory digest entries
    restorecon_xattr -D /etc/
    CHECK_RESULT $? 0 0 "failed to delete all security.sehash directory digest entries"
    #do not read /proc/mounts to obtain a list of non-seclabel mounts to be excluded from relabeling checks.  
    restorecon_xattr -m /proc/mounts
    CHECK_RESULT $? 0 0 "read /proc/mounts to obtain a list of non-seclabel mounts to be excluded from relabeling checks"
    LOG_INFO "End to run test."
}

# 后置处理，恢复测试环境
function post_test() {
    LOG_INFO "Start to restore the test environment."

    LOG_INFO "Nothing to do."

    LOG_INFO "End to restore the test environment."
}

main "$@"
