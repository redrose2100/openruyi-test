source "../common/common_lib.sh"
function run_test() {
    LOG_INFO "Start testing..."
    #Instead of checking the validity of a timestamp, remove it
    pam_timestamp_check -k
    CHECK_RESULT $? 0 0 "failed to remove the validity of a timestamp"
    #By default pam_timestamp_check checks or removes timestamps generated by pam_timestamp when the user authenticates as herself. When the user authenticates as a different user, the name of the timestamp file changes to accommodate this. target_user allows to specify this user name.
    pam_timestamp_check target
    CHECK_RESULT $? 7 0 "failed to pam_timestamp_check target"
    #Instead of returning validity using an exit status, loop indefinitely, polling regularly and printing the status on standard output
    nohup pam_timestamp_check -d >name.log 2>&1 &
    SLEEP_WAIT 10 "grep '7' name.log"
    CHECK_RESULT $? 0 0 "failed to print the status on standard output" 
    LOG_INFO "Finish test!"
}

    LOG_INFO "start environment cleanup."
    test -f /tmp/error.log && rm -f error.log
    test -f name.log && rm -rf name.log
    LOG_INFO "Finish environment cleanup!"
main "$@"
